// Скользящее окно для расчёта скорости загрузки — вместо мгновенной
// производной "байты с прошлого тика / время с прошлого тика".
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ КУСОК ЛОГИКИ В updateUI. При заливке с
// высокой параллельностью чанки не завершаются равномерно: сеть делит одну
// и ту же пропускную способность между всеми параллельными потоками, и они
// склонны финишировать волнами (см. реальный лог с прода — десятки чанков
// подтверждаются в одну и ту же секунду). Раз в UI-тик (~200мс) может
// подтвердиться сразу несколько десятков мегабайт — а старый расчёт
// "(displayed - lastLoaded) / (now - lastT)" делил их на эти же 200мс,
// выдавая мгновенные всплески в сотни МБ/с, которых на самом деле не было:
// эти байты физически летели все предыдущие 15-20 секунд, а не за один тик.
//
// Решение — usреднять не по соседним тикам, а по окну в несколько секунд:
// разница байт между самой старой и самой новой точкой в окне, делённая на
// разницу времени между ними. Всплеск в 500 МБ за один тик размазывается по
// окну и даёт реалистичную цифру, а не то, что на скриншоте с прода
// выглядело как "30 → 300 МБ/с и обратно за секунду".
(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    Object.assign(root, factory());
  }
})(typeof window !== 'undefined' ? window : globalThis, function () {

  // pushByteSample добавляет {t, bytes} в буфер и отбрасывает точки старше
  // windowMs от последней — буфер всегда состоит только из точек, реально
  // попадающих в скользящее окно. Мутирует и возвращает тот же массив, чтобы
  // вызывающему коду не нужно было пересваивать переменную.
  function pushByteSample(samples, sample, windowMs) {
    samples.push(sample);
    const cutoff = sample.t - windowMs;
    while (samples.length > 1 && samples[0].t < cutoff) samples.shift();
    return samples;
  }

  // windowedRate — байт/сек между самой старой и самой новой точкой буфера.
  // Меньше двух точек или нулевая разница времени — скорость неизвестна (0),
  // а не Infinity/NaN, потому что вызывающий код проверяет just ">0".
  function windowedRate(samples) {
    if (samples.length < 2) return 0;
    const first = samples[0];
    const last = samples[samples.length - 1];
    const dt = (last.t - first.t) / 1000;
    if (dt <= 0) return 0;
    return (last.bytes - first.bytes) / dt;
  }

  return { pushByteSample, windowedRate };
});
