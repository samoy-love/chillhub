// Автоподбор параметров чанковой заливки (размер чанка и параллельность) по
// размеру файла — и адаптивная ширина окна, по которому считается скорость.
//
// ЗАЧЕМ. Дефолт «8 МБ / 6 потоков» стоял независимо от того, заливают 30 МБ
// или 15 ГБ, а рядом был слайдер до 100 потоков без единой подсказки, что
// значения выше десятка делают только хуже. Ручной подбор через карточку
// «Тест параметров загрузки» честно меряет канал, но стоит десятки минут и
// гигабайты трафика — для обычной заливки нужен разумный ответ сразу, без
// прогона.
//
// ПОЧЕМУ ЧИСЛА ТАКИЕ — три ограничения, между которыми зажат ответ:
//
//   1. Снизу размер чанка ограничен накладными расходами: каждый чанк — это
//      отдельный PUT со своим round-trip и записью на диск. Чанки по 1 МБ на
//      быстром канале превращают заливку в тысячи запросов, и время уходит в
//      них, а не в передачу.
//   2. Сверху — ценой ретрая и ровностью хвоста. Сорванный чанк перезаливается
//      целиком, поэтому 512 МБ чанк на нестабильном канале может не долететь
//      никогда. И если чанков меньше нескольких на поток, последняя «волна»
//      получается рваной: часть потоков закончила, один дотягивает свой
//      кусок, канал стоит.
//   3. Параллельность сверху ограничена не сервером, а браузером: HTTP/1.1
//      держит 6 соединений на хост, и седьмой XHR просто встаёт в очередь.
//      Он при этом создан и посчитан как «активный», но не шлёт ни байта и не
//      даёт ни одного upload.onprogress — снаружи это выглядит как замерший
//      прогресс, а когда очередь наконец доходит до него, он одним рывком
//      сбрасывает в сокет мегабайты, и на графике появляется зуб. Ровно это
//      и происходило на «16 потоков / 16 МБ»: фризы и пила.
//
// Вынесено отдельным CommonJS-модулем по той же причине, что upload-bench.js
// и chunk-upload.js: только require()-имый файл c8 считает построчно.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    Object.assign(root, factory());
  }
})(typeof window !== 'undefined' ? window : globalThis, function () {

  // Границы размера чанка. Это не тот же диапазон, что в <select> (там 64 КБ …
  // 512 МБ) — руками выставить край по-прежнему можно, но автоподбор в него
  // никогда не уходит: за пределами [1 МБ, 32 МБ] проигрыш по одному из двух
  // ограничений выше начинается раньше, чем выигрыш по другому.
  const MIN_CHUNK = 1 << 20;
  const MAX_CHUNK = 32 << 20;

  // Сколько «волн» чанков должно уложиться в заливку: chunks ≈ waves × потоки.
  // 12 — компромисс между накладными расходами (меньше волн — крупнее чанк) и
  // ровностью хвоста (меньше волн — заметнее простой в конце). При 6 потоках
  // это 72 чанка на файл любого размера, пока размер чанка не упёрся в границу.
  const TARGET_WAVES = 12;

  // Предел одновременных соединений на хост. HTTP/1.1 — жёсткие 6 у всех
  // браузеров; по HTTP/2 запросы мультиплексируются в одно TCP-соединение,
  // и лимит там не в соединениях, но толку от третьего десятка потоков всё
  // равно нет — канал один, а конкуренция за диск на сервере растёт.
  function connectionCap(protocol) {
    const p = String(protocol || '').toLowerCase();
    if (p === 'h2' || p === 'h3' || p.startsWith('http/2') || p.startsWith('http/3')) return 12;
    return 6;
  }

  // Параллельность по размеру файла: на мелком файле лишние потоки не успевают
  // ничего разогнать (весь файл укладывается в несколько чанков), на крупном
  // упираемся в предел соединений. Пороги те же, что у planChunks на сервере
  // (server/internal/adminapi/builds/chunked.go), чтобы клиент и сервер не
  // расходились в оценке одного и того же файла.
  function pickConcurrency(fileSize, protocol) {
    const size = Math.max(0, Number(fileSize) || 0);
    let c;
    if (size <= 64 << 20) c = 2;
    else if (size <= 512 << 20) c = 4;
    else c = 6;
    return Math.min(c, connectionCap(protocol));
  }

  // nearestOption — ближайшее к target значение из списка. Отдельно от
  // pickClosestChunkOption в upload-bench.js: тот работает по всему списку
  // <select>, а здесь список предварительно обрезан границами автоподбора.
  function nearestOption(values, target) {
    let best = null, bestDiff = Infinity;
    for (const v of values) {
      const diff = Math.abs(v - target);
      if (diff < bestDiff) { bestDiff = diff; best = v; }
    }
    return best;
  }

  // pickUploadParams — главная функция модуля: по размеру файла (и, если
  // известен, протоколу соединения) возвращает { chunkSize, concurrency,
  // chunks }. chunkOptions, если передан, — значения <select>: ответ
  // округляется к ближайшему из них, потому что выставить в UI произвольное
  // число всё равно нельзя.
  function pickUploadParams(fileSize, opts) {
    const o = opts || {};
    const size = Math.max(0, Number(fileSize) || 0);
    let concurrency = pickConcurrency(size, o.protocol);

    let chunkSize = Math.round(size / (concurrency * TARGET_WAVES));
    chunkSize = Math.min(MAX_CHUNK, Math.max(MIN_CHUNK, chunkSize));
    if (o.chunkOptions && o.chunkOptions.length) {
      const inRange = o.chunkOptions.filter((v) => v >= MIN_CHUNK && v <= MAX_CHUNK);
      chunkSize = nearestOption(inRange.length ? inRange : o.chunkOptions, chunkSize);
    }

    // Файл меньше двух чанков на поток — потоки нечем занять, и лишние только
    // делают хвост рваным. Пустой файл до заливки не доходит, но 0 чанков не
    // должен превратиться в 0 потоков.
    const chunks = Math.max(1, Math.ceil(size / chunkSize));
    if (chunks < concurrency * 2) concurrency = Math.max(1, Math.floor(chunks / 2));

    return { chunkSize, concurrency, chunks };
  }

  // rateWindowMs — ширина скользящего окна для расчёта скорости, подобранная
  // под то, как часто вообще приходят подтверждения чанков.
  //
  // Фиксированные 5 секунд из rate-estimator.js хороши, пока чанк долетает за
  // доли секунды. На чанках в сотни мегабайт подтверждения приходят раз в
  // десяток секунд, и в окно попадает один-два рывка буфера сокета вместо
  // усреднения многих — то есть окно перестаёт делать ровно то, ради чего
  // заведено, и цифра снова начинает прыгать. Берём четыре типичных
  // интервала между подтверждениями: этого хватает, чтобы рывок отдельного
  // чанка растворился, и мало, чтобы цифра не отставала от реальности.
  //
  // Медиана, а не среднее: один ретрай с паузой в несколько секунд иначе
  // раздувает окно до потолка и держит его там до конца заливки.
  function rateWindowMs(intervalsMs, opts) {
    const o = opts || {};
    const minMs = o.minMs || 5000;
    const maxMs = o.maxMs || 20000;
    const arr = (intervalsMs || []).filter((n) => Number.isFinite(n) && n > 0).sort((a, b) => a - b);
    if (!arr.length) return minMs;
    const median = arr[Math.floor(arr.length / 2)];
    return Math.min(maxMs, Math.max(minMs, Math.round(median * 4)));
  }

  return {
    pickUploadParams, pickConcurrency, connectionCap, rateWindowMs,
    MIN_CHUNK, MAX_CHUNK, TARGET_WAVES,
  };
});
