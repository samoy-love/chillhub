// Get must order the gallery: pinned games first, then by the operator's
// Order, then by GameID for anything left tied — never the order the JSON
// file happened to list entries in.
func TestGetSortsPinnedThenOrderThenGameID(t *testing.T) {
	h := New(t.TempDir())
	saveRegistry(t, h, []Entry{
		{GameID: "z-unpinned", Order: 0},
		{GameID: "b-pinned-2", Pinned: true, Order: 2},
		{GameID: "a-pinned-2", Pinned: true, Order: 2},
		{GameID: "pinned-1", Pinned: true, Order: 1},
		{GameID: "a-unpinned", Order: 0},
	})

	got := decodeItems(t, h.Get, httptest.NewRequestWithContext(t.Context(), http.MethodGet, "/admin/api/games", nil))
	want := []string{"pinned-1", "a-pinned-2", "b-pinned-2", "a-unpinned", "z-unpinned"}
	if len(got) != len(want) {
		t.Fatalf("got %d entries, want %d: %+v", len(got), len(want), got)
	}
	for i, gid := range want {
		if got[i].GameID != gid {
			t.Fatalf("position %d = %q, want %q (full order: %+v)", i, got[i].GameID, gid, got)
		}
	}
}

// saveRegistry posts a list and fails the test if it is not stored.
func saveRegistry(t *testing.T, h *Handlers, items []Entry) {
	t.Helper()
	body, err := json.Marshal(struct {
		Items []Entry `json:"items"`
	}{Items: items})
	if err != nil {
		t.Fatal(err)
	}
	w := httptest.NewRecorder()
	r := httptest.NewRequestWithContext(t.Context(), http.MethodPost, "/admin/api/games/save", strings.NewReader(string(body)))
	h.Save(w, r)
	if w.Code != http.StatusOK {
		t.Fatalf("Save returned %d: %s", w.Code, w.Body.String())
	}
}

// A bad gameId must be refused AT THE SAVE, not quietly dropped when the public
// API reads the file later.
//
// Every id in the registry becomes a path component. The reader does drop
// unusable ones, but dropping is a silent cure: a typo made the game vanish
// from the launcher while the panel still said "saved", and the operator had no
// way to connect the two. Refusing the write names the offending entry at once.
func TestSaveRejectsUnsafeGameID(t *testing.T) {
	for _, bad := range []string{"../../etc", "bad id", "", "a/b", "game.id", "игра"} {
		h := New(t.TempDir())
		body, err := json.Marshal(struct {
			Items []Entry `json:"items"`
		}{Items: []Entry{{GameID: "ok-game"}, {GameID: bad}}})
		if err != nil {
			t.Fatal(err)
		}

		w := httptest.NewRecorder()
		r := httptest.NewRequestWithContext(t.Context(), http.MethodPost, "/admin/api/games/save", strings.NewReader(string(body)))
		h.Save(w, r)

		if w.Code != http.StatusBadRequest {
			t.Errorf("Save accepted gameId %q with %d", bad, w.Code)
			continue
		}
		// Nothing may be written: a partially applied save would drop the valid
		// entry the operator sent alongside the bad one.
		if _, err := os.Stat(filepath.Join(h.root, "manifests", "_registry", "games.json")); err == nil {
			t.Errorf("gameId %q was refused but the registry was written anyway", bad)
		}
	}
}

