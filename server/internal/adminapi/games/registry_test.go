// decodeItems runs a handler and decodes the {"items":[...]} envelope every games
// endpoint answers with.
func decodeItems(t *testing.T, fn http.HandlerFunc, r *http.Request) []Entry {
	t.Helper()
	w := httptest.NewRecorder()
	fn(w, r)
	if w.Code != http.StatusOK {
		t.Fatalf("handler returned %d: %s", w.Code, w.Body.String())
	}
	var out struct {
		Items []Entry `json:"items"`
	}
	if err := json.Unmarshal(w.Body.Bytes(), &out); err != nil {
		t.Fatalf("body is not the items envelope: %v (%s)", err, w.Body.String())
	}
	return out.Items
}

// withManifestDirs creates manifests/<name>/ for each name and returns the root.
func withManifestDirs(t *testing.T, names ...string) string {
	t.Helper()
	root := t.TempDir()
	for _, n := range names {
		if err := os.MkdirAll(filepath.Join(root, "manifests", n), 0o750); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// The registry is what the launcher's game list is built from. On a fresh server
// it does not exist yet, and the admin must still see the games that have
// manifests — otherwise the panel looks empty on a server that is serving games.
func TestGetAutogeneratesRegistryOnFirstUse(t *testing.T) {
	root := withManifestDirs(t, "lethal-company", "raft")
	h := New(root)

	items := decodeItems(t, h.Get, httptest.NewRequestWithContext(t.Context(), http.MethodGet, "/admin/api/games", nil))
	if len(items) != 2 {
		t.Fatalf("autogenerated registry holds %d games, want 2: %+v", len(items), items)
	}

	// It must also be persisted: the admin edits titles and paths on top of it.
	if _, err := os.Stat(filepath.Join(root, "manifests", "_registry", "games.json")); err != nil {
		t.Fatalf("the autogenerated registry was not written: %v", err)
	}
}

// Service directories are not games. 'launcher' in particular holds the launcher's
// own build manifests — listing it would put the launcher into its own game list.
func TestServiceDirectoriesAreNotGames(t *testing.T) {
	h := New(withManifestDirs(t, "launcher", "repo", "_registry", "real-game", "LAUNCHER"))

	for _, e := range h.FromManifests() {
		switch strings.ToLower(e.GameID) {
		case "launcher", "repo", "_registry":
			t.Errorf("%q was listed as a game", e.GameID)
		}
	}
	if got := len(h.FromManifests()); got != 1 {
		t.Fatalf("scan found %d games, want only real-game: %+v", got, h.FromManifests())
	}
}

