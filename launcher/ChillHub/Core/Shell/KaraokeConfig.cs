namespace ChillHub.Core.Shell {
    using System;

    /// <summary>
    /// Централизованная конфигурация караоке — все параметры поведения в одном месте.
    /// </summary>
    internal sealed class KaraokeConfig {
        // Тайминг подобран под саму песню — 4:10 (250 с) на полный круг текста: 91 строка
        // (20 пустых — паузы между куплетами), 2307 символов.
        //
        // Печать — 60 мс на символ (16 симв/с): это темп живого набора, медленнее он
        // читается как «зависло». На неё уходит 2307·60 = 138 с. Остальные 112 с делятся
        // на 91 строку по ~1,2 с паузы с угасанием — примерно столько строка и звучит
        // в записи после того, как её дочитали. Итог: 138 + 91·1,22 = 249 с.
        //
        // Именно такое распределение, а не равномерные 74 мс на символ без пауз: короткие
        // строки припева («Моя игра, моя игра») в песне тянутся так же долго, как длинные
        // строки куплета, — пауза после строки это и передаёт, а ровная печать нет.
        //
        // Печать идёт только пока окно видно и активно, поэтому по стенным часам круг
        // длиннее — но темп совпадает с записью.
        internal int CharIntervalMs { get; init; } = 60;

        // Пауза после дописанной строки (мс) — см. расчёт выше
        internal int PauseAfterLineMs { get; init; } = 1000;

        // Угасание дописанной строки перед следующей (мс)
        internal int FadeOutMs { get; init; } = 220;

        // Ограничение на макс. число символов, добавляемых за один тик (чтобы не "перескакивало" строку)
        internal int MaxAdvanceCharsPerTick { get; init; } = 1;

        // Интервал тиков таймера (мс) — немного чаще печати, чтобы не пропускать символы
        internal int TimerTickMs => Math.Max(10, this.CharIntervalMs / 2);
    }
}
