namespace ChillHub.Core.Shell {
    using System;

    /// <summary>
    /// Централизованная конфигурация караоке — все параметры поведения в одном месте.
    /// </summary>
    internal sealed class KaraokeConfig {
        // Тайминг подобран под саму песню — 4:10 (250 с) на полный круг текста: 91 строка,
        // из них 20 пустых — границы куплетов, 2307 символов.
        //
        // Строки печатаются быстро (45 мс на символ, ~22 симв/с) и с короткой паузой,
        // а бюджет времени песни выбирают ПУСТЫЕ строки: в записи между куплетами идут
        // проигрыши, и именно там строка стоит долго. Медленная ровная печать с длинными
        // паузами после каждой строки читалась как заикание.
        //
        //   печать   2307 × 45 мс                = 104 с
        //   строки   71 × (450 + 150) мс          =  43 с
        //   куплеты  20 × (5000 + 150) мс         = 103 с
        //   итого                                  = 250 с
        //
        // Печать идёт только пока окно видно и активно, поэтому по стенным часам круг
        // длиннее — но темп совпадает с записью.
        internal int CharIntervalMs { get; init; } = 45;

        // Пауза после дописанной строки (мс)
        internal int PauseAfterLineMs { get; init; } = 450;

        // Пауза на пустой строке — проигрыш между куплетами (мс)
        internal int PauseAfterEmptyLineMs { get; init; } = 5000;

        // Угасание дописанной строки перед следующей (мс)
        internal int FadeOutMs { get; init; } = 150;

        // Ограничение на макс. число символов, добавляемых за один тик (чтобы не "перескакивало" строку)
        internal int MaxAdvanceCharsPerTick { get; init; } = 2;

        // ТИКАЕМ РОВНО В ТЕМП ПЕЧАТИ, А НЕ ВДВОЕ ЧАЩЕ.
        //
        // Раньше таймер будил диспетчер каждые 22 мс — сорок пять раз в секунду всё время,
        // пока окно активно, то есть и когда лаунчер просто стоит открытым. Половина этих
        // тиков не добавляла ни одного символа: PlanAdvance считает буквы по прошедшему
        // времени, и при интервале вдвое короче печати он через раз возвращает ноль.
        //
        // Теперь тик совпадает с шагом печати, а MaxAdvanceCharsPerTick=2 покрывает
        // случай, когда тик задержался: пропущенное дописывается следующим тиком, темп
        // остаётся прежним. Пробуждений — вдвое меньше.
        internal int TimerTickMs => Math.Max(10, this.CharIntervalMs);
    }
}
