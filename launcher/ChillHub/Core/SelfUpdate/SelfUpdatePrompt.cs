namespace ChillHub.Core.SelfUpdate {
    /// <summary>
    /// Когда показывать диалог обновления лаунчера.
    /// <para>
    /// НАЙДЕННОЕ ОБНОВЛЕНИЕ НЕ ДОЛЖНО ТЕРЯТЬСЯ. Фоновая проверка ходит по таймеру
    /// независимо от того, видно ли окно, а показать диалог свёрнутому окну нельзя —
    /// и результат такой проверки просто выбрасывался. Вернувшись к лаунчеру, человек
    /// не видел ничего: окно активации ходило за версией не чаще раза в десять минут,
    /// то есть обычно молчало.
    /// </para>
    /// <para>
    /// Оба правила ниже — чистые функции, потому что проверять их на живом окне
    /// WPF нечем, а ошибка в них выглядит как «обновление не приходит» и живёт до
    /// первой жалобы.
    /// </para>
    /// </summary>
    internal static class SelfUpdatePrompt {
        /// <summary>
        /// Подходящий ли сейчас момент для модального диалога.
        /// <para>
        /// Свёрнутому или спрятанному в трей окну показывать некому, а посреди
        /// закачки или проверки файлов — не время: работа идёт минутами, и диалог
        /// поверх неё выглядит как требование бросить начатое.
        /// </para>
        /// </summary>
        /// <param name="windowVisible">Окно на экране (не в трее).</param>
        /// <param name="minimized">Окно свёрнуто.</param>
        /// <param name="busy">В очереди есть работа: закачка или проверка файлов.</param>
        /// <returns>true, если диалог можно показать прямо сейчас.</returns>
        internal static bool CanShowNow(bool windowVisible, bool minimized, bool busy)
            => windowVisible && !minimized && !busy;

        /// <summary>
        /// Идти ли за версией по возврату фокуса на окно.
        /// <para>
        /// Обычно — не чаще, чем разрешит ограничитель: Alt+Tab между окнами даёт
        /// десятки активаций в минуту, и на каждой уходил бы запрос к серверу.
        /// </para>
        /// <para>
        /// Но если обновление УЖЕ найдено и ждёт подходящего момента, ограничитель
        /// молчит: показать уже известное ничего не стоит, а ждать с ним десять минут
        /// — это ровно то, из-за чего окно обновления не появлялось при возврате к
        /// лаунчеру.
        /// </para>
        /// </summary>
        /// <param name="updateWaiting">Обновление найдено и ждёт показа.</param>
        /// <param name="throttleAllows">Ограничитель частоты разрешает запрос.</param>
        /// <returns>true, если проверку нужно запустить.</returns>
        internal static bool ShouldCheckOnActivate(bool updateWaiting, bool throttleAllows)
            => updateWaiting || throttleAllows;
    }
}
