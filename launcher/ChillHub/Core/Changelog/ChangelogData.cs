        /// обещание «у каждой выкатки есть запись» проверяется именно по этому списку.
        /// </summary>
        public static IReadOnlyList<ChangelogRelease> Releases => All;

        /// <summary>
        /// То, что видит игрок: выпуски, в которых лаунчер действительно менялся.
        /// Строка «в этой версии ничего не изменилось» — не новость, а шум, и в окне
        /// она вытесняла бы собой настоящие записи.
        /// </summary>
        public static IReadOnlyList<ChangelogRelease> Visible { get; } = BuildVisible(All);

        private static IReadOnlyList<ChangelogRelease> BuildVisible(IReadOnlyList<ChangelogRelease> all) {
            var visible = new List<ChangelogRelease>(all.Count);
            foreach (var release in all) {
                if (!release.Technical) {
                    visible.Add(release);
                }
            }

            return visible;
        }
