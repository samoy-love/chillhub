        public static IReadOnlyList<ChangelogRelease> Visible { get; } = BuildVisible(All);

        private static IReadOnlyList<ChangelogRelease> BuildVisible(IReadOnlyList<ChangelogRelease> all) {
            var visible = new List<ChangelogRelease>(all.Count);
            foreach (var release in all) {
                if (!release.Technical) {
                    visible.Add(release);
                }
            }

            return visible;
        }
