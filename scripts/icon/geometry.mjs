// Геометрия значка Chill Hub. Один источник правды для .ico, .png и .svg.
//
// Значок держится на трёх плоскостях: тёмная плашка, обводка цвета углей и
// светлый знак. Замеры контраста объясняют, зачем нужна каждая:
//
//   знак / плашка           6,12  — знак читается всегда
//   обводка / тёмная панель 4,40  — на тёмном фоне силуэт даёт обводка
//   плашка / светлая панель 15,08 — на светлом фоне силуэт даёт плашка
//   плашка / тёмная панель   1,03 — на тёмном плашка не видна вовсе
//   знак / обводка           1,35 — знак и обводка почти одной светлоты!
//
// Отсюда два правила.
//
// Первое: обводка несущая. Её нельзя рисовать штрихом — штрих размазывается
// сглаживанием и на 16 px теряет половину плотности. Она рисуется заливкой и
// прибивается к целым пикселям на каждом размере.
//
// Второе: знак и обводка почти одной светлоты, поэтому стыкаться им нельзя
// ни на одном размере — иначе они сливаются в одно пятно. Между ними всегда
// остаётся плашка, и это поле проверяется тестом, а не глазом.

export const COLORS = {
  plate: '#2a1a12',
  ring: '#d1663c',
  mark: '#e5825b',
};

// Значок не масштабируется линейно: обводка обязана быть относительно толще
// на мелких размерах, иначе теряется, и тоньше на крупных, иначе значок
// читается рамкой, а не знаком. Поэтому пропорции заданы таблицей на каждый
// размер, а не одним коэффициентом.
//
//   поле — отступ от края холста до плашки
//   ring — толщина обводки
//   r    — радиус скругления плашки
//
// Поля вокруг знака в таблице НЕТ: они выводятся вместе с полосами (см. fit).
// Задавать их числом означало выбирать между «знак сидит в рамке» и «полосы
// достаточно толстые» вслепую — а выбирать надо оба разом.
const TABLE = {
  16: { pad: 0, ring: 1, r: 3 },
  24: { pad: 0, ring: 2, r: 4 },
  32: { pad: 0, ring: 2, r: 5 },
  48: { pad: 1, ring: 3, r: 8 },
  64: { pad: 2, ring: 4, r: 10 },
  96: { pad: 3, ring: 5, r: 15 },
  128: { pad: 4, ring: 6, r: 20 },
  256: { pad: 8, ring: 10, r: 40 },
};

// Знак: доли внутреннего окна. Полосы одинаковой высоты, лесенка по ширине.
const BAR_W = [1, 0.71, 0.43];
const BAR_H = 0.24;

const snap = (v, min = 0) => Math.max(min, Math.round(v));

// Промежуточный размер (например 28 в шапке сайта) берёт пропорции ближайшего
// табличного и пересчитывает их — так значок остаётся собой на любом числе.
function metrics(size) {
  if (TABLE[size]) return TABLE[size];
  const known = Object.keys(TABLE).map(Number);
  const near = known.reduce((a, b) => (Math.abs(b - size) < Math.abs(a - size) ? b : a));
  const k = size / near;
  const m = TABLE[near];
  return {
    pad: snap(m.pad * k),
    ring: snap(m.ring * k, 1),
    r: snap(m.r * k, 2),
  };
}

// Поле вокруг знака и толщина полос подбираются вместе. Три требования тянут
// в разные стороны, и удовлетворить их можно только разом:
//
//   1. поле одинаково со всех четырёх сторон и не скачет от размера к размеру
//      — иначе на одном размере знак сидит в рамке, а на соседнем распирает её;
//   2. полосы нужной толщины — не тощие, но и не распирающие рамку;
//   3. всё в целых пикселях — на 16 px дробность видна сразу.
//
// Порядок разрешения конфликта: сначала поле (пункт 1), потом толщина (пункт 2).
// Обратный порядок пробовали — поле уезжает к минимуму на крупных размерах и
// к максимуму на мелких, и знак выглядит то распёртым, то потерянным.
const MARK_W = 0.62; // ширина самой длинной полосы, доля холста
const BAR_AIM = { 3: 0.155, 2: 0.22 }; // толщина полосы, доля холста
const BLOCK_AIM = 0.55; // высота всего знака, доля холста
const RHYTHM = [0.22, 0.55]; // просвет в долях полосы
const MIN_MARGIN = 0.04; // поле от знака до обводки, доля холста

// Знак — компактная группа по центру плашки, а не заполнение её целиком.
// Три полосы должны читаться одним блоком, поэтому просветы между ними явно
// уже полей вокруг: своих от чужого отделяет расстояние.
//
// Целых пикселей это касается вдвойне: чтобы блок встал ровно по центру,
// остаток от вычитания его высоты из внутреннего окна обязан быть чётным —
// иначе поля сверху и снизу разъедутся на пиксель.
function pickBlock(size, inner, count) {
  const barAim = BAR_AIM[count] * size;
  const blockAim = BLOCK_AIM * size;
  const gapMin = size >= 24 ? 2 : 1;
  const minMargin = Math.max(1, Math.round(size * MIN_MARGIN));
  let best = null;
  for (let h = 1; h <= Math.floor(inner / count); h++) {
    for (let gap = gapMin; gap <= Math.floor(h * RHYTHM[1]); gap++) {
      if (gap / h < RHYTHM[0]) continue;
      const block = count * h + (count - 1) * gap;
      if ((inner - block) % 2 !== 0) continue;
      const margin = (inner - block) / 2;
      if (margin < minMargin) continue;
      // Ближе к желаемой высоте блока, потом — к желаемой толщине полосы.
      const cost = (Math.abs(block - blockAim) / size) * 2 + Math.abs(h - barAim) / size;
      if (!best || cost < best.cost) best = { h, gap, margin, cost };
    }
  }
  return best;
}

// Ширина знака подгоняется так, чтобы поля слева и справа тоже вышли целыми.
function pickWidth(size, inner) {
  const minMargin = Math.max(1, Math.round(size * MIN_MARGIN));
  let w = Math.round(size * MARK_W);
  if ((inner - w) % 2 !== 0) w -= 1;
  while (w > 1 && (inner - w) / 2 < minMargin) w -= 2;
  return w;
}

export function geometry(size) {
  const { pad, ring, r: radius } = metrics(size);
  const barRadius = snap(size * 0.012, 0);

  const plate = { x: pad, y: pad, w: size - 2 * pad, h: size - 2 * pad, r: radius };
  const inner = {
    x: plate.x + ring,
    y: plate.y + ring,
    w: plate.w - 2 * ring,
    h: plate.h - 2 * ring,
    r: Math.max(1, radius - ring),
  };

  // Трёх полос на 16 px не бывает: полоса и просвет обязаны быть целыми,
  // и на такой высоте лесенка сливается в кашу. Там знак из двух полос —
  // силуэт узнаётся, а пиксели остаются чистыми.
  const count = size <= 16 ? 2 : 3;
  const widths = count === 2 ? [1, 0.62] : BAR_W;

  const f = pickBlock(size, inner.h, count);
  if (!f) throw new Error(`значок ${size}: знак не встаёт по центру в целых пикселях`);
  const markW = pickWidth(size, inner.w);

  const boxX = inner.x + (inner.w - markW) / 2;
  const top = inner.y + f.margin;

  const bars = widths.map((k, i) => ({
    x: boxX,
    y: top + i * (f.h + f.gap),
    w: Math.max(1, Math.round(markW * k)),
    h: f.h,
    r: Math.min(barRadius, Math.floor(f.h / 2)),
  }));

  return { size, plate, inner, bars, ring, clear: (inner.w - markW) / 2 };
}

