// Геометрия значка Chill Hub. Один источник правды для .ico, .png и .svg.
//
// Знак — открытая буква C и точка в её разрыве. C — от Chill, точка — хаб,
// место, куда всё сходится. Белый знак стоит на скруглённой плашке с
// диагональным градиентом из красок лаунчера: сверху-слева его акцент под
// курсором #8f73ff, снизу-справа нажатая заливка #5a3fcc.
//
// Почему без канта. Насыщенный фиолетовый сам отделяется и от тёмной панели
// задач, и от светлой вкладки браузера — светлая обводка, которая держала
// прошлые значки на тёмном фоне, здесь не нужна, а вокруг знака она читалась
// дешёвой рамкой. Замеры по середине градиента (#7458ee):
//
//   плашка / тёмная панель задач   3,3  — плашка видна и без канта
//   плашка / светлая вкладка        4,4  — и на светлом тоже
//   знак / низ градиента            7,0  — там, где знак тоньше всего
//   знак / верх градиента           3,6  — там только толстая дуга C
//
// Цифры проверяет тест, а не глаз.

export const COLORS = {
  top: '#8f73ff',
  bottom: '#5a3fcc',
  mark: '#ffffff',
};

// Размеры заданы таблицей на каждый размер, а не одним коэффициентом: края
// кольца и точки обязаны попадать на границы пикселей, иначе на 16 px знак
// размывается в серое пятно. Центр знака — центр холста, радиусы целые, поэтому
// крайние точки кольца слева, сверху и снизу ложатся ровно на сетку.
//
//   pad — прозрачное поле вокруг плашки
//   r   — скругление плашки, около четверти её стороны
//   ro  — внешний радиус кольца, около 0,3 холста
//   sw  — толщина кольца, около 1/8 холста; точка того же диаметра
const TABLE = {
  16: { pad: 0, r: 4, ro: 5, sw: 2 },
  24: { pad: 0, r: 6, ro: 7, sw: 3 },
  32: { pad: 1, r: 7, ro: 9, sw: 4 },
  48: { pad: 2, r: 10, ro: 14, sw: 6 },
  64: { pad: 3, r: 14, ro: 19, sw: 8 },
  96: { pad: 4, r: 21, ro: 28, sw: 12 },
  128: { pad: 6, r: 28, ro: 38, sw: 15 },
  256: { pad: 12, r: 56, ro: 76, sw: 30 },
};

// Промежуточный размер (например 28 в шапке сайта) берёт пропорции ближайшего
// табличного и пересчитывает их — так значок остаётся собой на любом числе.
function metrics(size) {
  if (TABLE[size]) return TABLE[size];
  const known = Object.keys(TABLE).map(Number);
  const near = known.reduce((a, b) => (Math.abs(b - size) < Math.abs(a - size) ? b : a));
  const k = size / near;
  const m = TABLE[near];
  const snap = (v, min) => Math.max(min, Math.round(v));
  return { pad: snap(m.pad * k, 0), r: snap(m.r * k, 2), ro: snap(m.ro * k, 4), sw: snap(m.sw * k, 2) };
}

// Просвет между концами дуги и точкой: не меньше полутора пикселей на мелких
// размерах — на одном пикселе точка прилипала к букве и C читалась с хвостом.
const CLEAR = 0.055;

export function geometry(size) {
  const { pad, r, ro, sw } = metrics(size);
  const plate = { x: pad, y: pad, w: size - 2 * pad, h: size - 2 * pad, r };

  const cx = size / 2;
  const cy = size / 2;
  const ri = ro - sw;
  const mid = (ro + ri) / 2;
  const dot = { cx: cx + mid, cy, r: sw / 2 };

  // Полуугол разрыва: дуга кончается скруглённым торцом радиуса sw/2, и между
  // торцом и точкой должен остаться просвет clear. Отсюда хорда между центром
  // торца и центром точки и угол, который она стягивает на средней окружности.
  const clear = Math.max(1.5, size * CLEAR);
  const chord = sw / 2 + dot.r + clear;
  const phi = 2 * Math.asin(Math.min(1, chord / (2 * mid)));

  return { size, plate, arc: { cx, cy, ro, ri, mid, sw, phi }, dot, clear };
}

// Центры торцов дуги — на средней окружности под углами ±phi от точки.
export function caps(g) {
  const { cx, cy, mid, phi } = g.arc;
  return [
    { x: cx + mid * Math.cos(phi), y: cy - mid * Math.sin(phi) },
    { x: cx + mid * Math.cos(phi), y: cy + mid * Math.sin(phi) },
  ];
}

